  function buildUnionLetters(words, extras) {
    const max = {};
    for (const w of words) {
      const c = {};
      for (const ch of w) c[ch] = (c[ch] || 0) + 1;
      for (const [k, v] of Object.entries(c)) max[k] = Math.max(max[k] || 0, v);
    }
    const arr = [];
    for (const [k, v] of Object.entries(max)) {
      for (let i = 0; i < v; i++) arr.push(k.toUpperCase());
    }
    if (Array.isArray(extras)) {
      extras.forEach(ch => arr.push(ch.toUpperCase()));
    }
    return arr;
  }

