  // Đồng bộ toàn bộ từ ghép từ MERGE_LEVELS vào DICT để hỗ trợ cả Nối chữ & từ thưởng
  MERGE_LEVELS.forEach((lvl) => {
    lvl.pairs.forEach(([, , combined, meaning]) => {
      const k = stripTones(combined);
      if (k && !DICT[k]) {
        DICT[k] = { word: combined, meaning };
      }
    });
  });

  // Tăng độ khó Ghép Từ Tiếng Việt: nâng mỗi phiên lên 8–10 mảnh bẫy (decoys) không tạo thành từ hợp lệ với mảnh thật
  (function enrichMergeDecoys() {
    const allPieces = Array.from(
      new Set(MERGE_LEVELS.flatMap((l) => l.pairs.flatMap(([a, b]) => [a, b])))
    );
    MERGE_LEVELS.forEach((lvl) => {
      const targetDecoyCount = lvl.tier === "Nâng cao" ? 10 : 8;
      const ownPieces = new Set(lvl.pairs.flatMap(([a, b]) => [a, b]));
      const existing = new Set(lvl.decoys || []);
      const candidates = shuffleArray(allPieces);
      for (const cand of candidates) {
        if (existing.size >= targetDecoyCount) break;
        if (ownPieces.has(cand) || existing.has(cand)) continue;
        const candNorm = stripTones(cand);
        let createsValid = false;
        for (const p of ownPieces) {
          const pNorm = stripTones(p);
          if (DICT[pNorm + candNorm] || DICT[candNorm + pNorm]) {
            createsValid = true;
            break;
          }
        }
        if (!createsValid) existing.add(cand);
      }
      lvl.decoys = Array.from(existing);
    });
  })();

  function shuffleArray(arr) {
    const copy = arr.slice();
    for (let i = copy.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  }

  function buildConnectLevel(lvl, avoidWords) {
    const allValid = lvl.targets.filter((w) => DICT[w]);
    const avoidSet = new Set(Array.isArray(avoidWords) ? avoidWords : []);
    const freshWords = shuffleArray(allValid.filter((w) => !avoidSet.has(w)));
    const oldWords = shuffleArray(allValid.filter((w) => avoidSet.has(w)));
    const pool = [...freshWords, ...oldWords];
    let best = [];
    for (let attempt = 0; attempt < 60; attempt++) {
      const candidatePool = attempt === 0 ? pool : [...shuffleArray(freshWords), ...shuffleArray(oldWords)];
      const picked = [];
      for (const w of candidatePool) {
        if (picked.length >= 7) break;
        const candidate = [...picked, w];
        if (buildUnionLetters(candidate).length <= 16) {
          picked.push(w);
        }
      }
      if (picked.length > best.length) best = picked;
      if (best.length >= 6) break;
    }
    // Fallback an toàn nếu random chưa đủ 5 từ
    if (best.length < 5) {
      for (const w of pool) {
        if (!best.includes(w) && buildUnionLetters([...best, w]).length <= 16) {
          best.push(w);
        }
        if (best.length >= 6) break;
      }
    }
    const validTargets = best.sort((a, b) => a.length - b.length || a.localeCompare(b));
    const baseLetters = buildUnionLetters(validTargets);
    if (lvl.tier === "Nâng cao" && baseLetters.length < 16) {
      const filler = ["K", "P", "S", "B", "R", "V"].find((c) => !baseLetters.includes(c));
      if (filler) baseLetters.push(filler);
    }
    return {
      id: lvl.id,
      tier: lvl.tier,
      topic: lvl.topic,
      letters: baseLetters,
      targets: validTargets
    };
  }

  const CONNECT_LEVELS = RAW_CONNECT.map((lvl) => buildConnectLevel(lvl));

  function reshuffleLevel(id, avoidWords = []) {
    const rawIdx = RAW_CONNECT.findIndex((l) => l.id === id);
    if (rawIdx === -1) return null;
    CONNECT_LEVELS[rawIdx] = buildConnectLevel(RAW_CONNECT[rawIdx], avoidWords);
    return CONNECT_LEVELS[rawIdx];
  }

  return { DICT, CONNECT_LEVELS, MERGE_LEVELS, stripTones, reshuffleLevel };
